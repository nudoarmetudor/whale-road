"""Build js/data/coast.js from Natural Earth 1:50m land (public domain, via world-atlas).

Usage: python tools/build_map.py path/to/land-50m.json
Projection: simple conic-ish equirectangular centred on 55N, output in a 1000 x 760 box.
"""
import json, math, sys

LON0, LON1, LAT0, LAT1 = -26.0, 44.0, 38.0, 68.5
W = 1000
K = math.cos(math.radians(55))

def merc(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))

YT, YB = merc(LAT1), merc(LAT0)
H = W * (YT - YB) / math.radians((LON1 - LON0))
H = round(H)

def proj(lon, lat):
    x = (lon - LON0) / (LON1 - LON0) * W
    y = (YT - merc(lat)) / (YT - YB) * H
    return x, y

def dp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-9
    imax, dmax = 0, 0
    for i in range(1, len(pts) - 1):
        x, y = pts[i]
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n
        if d > dmax:
            imax, dmax = i, d
    if dmax > eps:
        return dp(pts[: imax + 1], eps)[:-1] + dp(pts[imax:], eps)
    return [pts[0], pts[-1]]

def clip(poly, x0, y0, x1, y1):
    """Sutherland-Hodgman clip of a ring to a rectangle."""
    def edge(pts, inside, inter):
        out = []
        for i in range(len(pts)):
            cur, prev = pts[i], pts[i - 1]
            if inside(cur):
                if not inside(prev):
                    out.append(inter(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(inter(prev, cur))
        return out
    def ix(xv):
        return lambda a, b: (xv, a[1] + (b[1] - a[1]) * (xv - a[0]) / (b[0] - a[0]))
    def iy(yv):
        return lambda a, b: (a[0] + (b[0] - a[0]) * (yv - a[1]) / (b[1] - a[1]), yv)
    pts = poly
    for ins, inter in ((lambda p: p[0] >= x0, ix(x0)), (lambda p: p[0] <= x1, ix(x1)),
                       (lambda p: p[1] >= y0, iy(y0)), (lambda p: p[1] <= y1, iy(y1))):
        if not pts:
            return []
        pts = edge(pts, ins, inter)
    return pts

def main(path):
    topo = json.load(open(path))
    sc, tr = topo["transform"]["scale"], topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        out = []
        for dx, dy in arc:
            x += dx; y += dy
            out.append((x * sc[0] + tr[0], y * sc[1] + tr[1]))
        arcs.append(out)

    def ring(idx):
        pts = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            pts.extend(a if not pts else a[1:])
        return pts

    paths = []
    for g in topo["objects"]["land"]["geometries"]:
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        for poly in polys:
            for r in poly:
                pts = ring(r)
                if not any(LON0 - 8 < lo < LON1 + 8 and LAT0 - 6 < la < LAT1 + 6 for lo, la in pts):
                    continue
                # clamp to a padded box so huge continents stay closed shapes
                pp = clip([proj(max(-60, min(100, lo + 360 if lo < -150 else lo)), max(-85, min(85, la))) for lo, la in pts], -30, -30, W + 30, H + 30)
                if len(pp) < 4:
                    continue
                m = len(pp) // 2
                pp = dp(pp[: m + 1], 0.9)[:-1] + dp(pp[m:], 0.9)
                if len(pp) < 4:
                    continue
                xs = [p[0] for p in pp]; ys = [p[1] for p in pp]
                if max(xs) - min(xs) < 3 and max(ys) - min(ys) < 3:
                    continue
                paths.append("M" + "L".join(f"{x:.0f},{y:.0f}" for x, y in pp) + "Z")
    d = "".join(paths)
    with open("js/data/coast.js", "w") as f:
        f.write("// Generated by tools/build_map.py from Natural Earth 1:50m land (public domain).\n")
        f.write(f"export const MAP_W = {W};\nexport const MAP_H = {H};\n")
        f.write(f"export const PROJ = {{lon0: {LON0}, lon1: {LON1}, lat0: {LAT0}, lat1: {LAT1}}};\n")
        f.write(f"export const COAST = \"{d}\";\n")
    print("paths", len(paths), "chars", len(d), "H", H)

if __name__ == "__main__":
    main(sys.argv[1])
